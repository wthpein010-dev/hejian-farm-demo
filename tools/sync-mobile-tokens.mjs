import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const css = readFileSync(new URL('prototype/styles.css', root), 'utf8');
const block = css.match(/:root\s*\{([^}]+)\}/)?.[1];
if (!block) throw new Error('Missing canonical CSS root tokens');
const declarations = [...block.matchAll(/(--[\w-]+)\s*:\s*([^;]+);/g)].map(([, name, value]) => `  ${name}: ${value};`);
const output = new URL('apps/mobile/src/styles/tokens.css', root);
mkdirSync(fileURLToPath(new URL('.', output)), { recursive: true });
const generated = `/* Generated by npm run tokens from prototype/styles.css. Do not edit. */\npage, :root {\n${declarations.join('\n')}\n}\n`;
if (process.argv.includes('--check')) {
  if (readFileSync(output, 'utf8') !== generated) throw new Error('Mobile token adapter is stale');
} else writeFileSync(output, generated);
