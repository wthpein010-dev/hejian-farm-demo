import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { fileURLToPath } from 'node:url';
const root = new URL('../', import.meta.url);
const css = readFileSync(new URL('prototype/styles.css', root), 'utf8');
const tokens = {Canvas:'canvas',Paper:'paper',Ink:'ink',Secondary:'secondary',Primary:'brand',Soft:'brand-soft',Accent:'accent',Line:'line',Danger:'danger',Warning:'warning',Focus:'focus',Muted:'muted',ScrollThumb:'scroll-thumb',Action:'action',Header:'header-warm'};
const fields = Object.entries(tokens).map(([name,key]) => {
  const value = css.match(new RegExp(`--${key}:\\s*(#[A-Fa-f0-9]{6})\\s*[;}]`))?.[1];
  if (!value) throw new Error(`Missing canonical token ${key}`);
  return `        public static readonly Color ${name} = Hex("${value}");`;
});
const source = `// Generated by tools/sync-unity-theme.mjs from prototype/styles.css. Do not edit.\nusing UnityEngine;\nnamespace Hegeng {\n    public static class FarmTheme {\n${fields.join('\n')}\n        static Color Hex(string value) { ColorUtility.TryParseHtmlString(value, out var color); return color; }\n    }\n}\n`;
const target = new URL('unity/Assets/Scripts/FarmTheme.cs', root);
if (process.argv.includes('--check')) {
  if (readFileSync(target,'utf8') !== source) throw new Error('Unity theme drift');
  console.log('Unity theme matches canonical CSS');
} else {
  mkdirSync(fileURLToPath(new URL('unity/Assets/Scripts/',root)),{recursive:true});
  writeFileSync(target,source);
  console.log('Unity theme generated');
}
